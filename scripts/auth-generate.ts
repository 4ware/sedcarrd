/**
 * Regenerates features/auth/db/schema.ts from the Better Auth config (re-run after adding plugins),
 * then patches it for drizzle-orm 1.x, where the classic `relations()` helper moved to
 * `drizzle-orm/_relations`. Afterwards: `bun run db:generate` to create a migration.
 */
export {};

const output = "features/auth/db/schema.ts";

// The CLI loads the auth config, which imports the current schema; start from an empty module
// so a stale or half-patched schema can't break generation.
await Bun.write(output, "export {};\n");

const cli = Bun.spawnSync(
  ["bunx", "auth@latest", "generate", "--config", "features/auth/lib/auth.cli.ts", "--output", output, "-y"],
  { stdout: "inherit", stderr: "inherit" },
);
if (cli.exitCode !== 0) process.exit(cli.exitCode ?? 1);

const source = await Bun.file(output).text();
const patched = source.replace(/import \{ relations \} from "drizzle-orm";/, 'import { relations } from "drizzle-orm/_relations";');
const header = "// Generated by `bun run auth:generate` (Better Auth CLI). Do not edit by hand.\n";
await Bun.write(output, header + patched);
console.log(`Patched ${output} for drizzle-orm 1.x`);
